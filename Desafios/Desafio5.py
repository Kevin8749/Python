#Faça um programa que leia um número inteiro e moste na tela o seu antecessor e seu sucessor
Num_Escolhido = int(input("\033[1;36;40m Escreva um número: "))
Antessesor = Num_Escolhido - 1
Sucessor = Num_Escolhido + 1
print(f"\n O sucessor do seu número é: {Sucessor}")
print(f"\n O antessessor do seu número é: {Antessesor}")